// Google Maps deep links. Built from name + address rather than coordinates
// on purpose: Maps resolves a hospital name reliably even if a line of the
// address is slightly off, whereas a wrong coordinate silently sends someone
// to the wrong place. No API key needed for any of these URL forms.
export function mapsQuery(h) {
  return `${h.name}, ${h.address}`
}

export function mapsDirectionsUrl(h) {
  return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(mapsQuery(h))}`
}

export function mapsEmbedUrl(h) {
  return `https://maps.google.com/maps?q=${encodeURIComponent(mapsQuery(h))}&output=embed`
}

